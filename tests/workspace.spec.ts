test('rotated signing identity produces a verifiable evidence export', async ({ page }) => {
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'HMAC rotation', exact: true }).click()
  await page.getByRole('button', { name: 'Rotate secret', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Rotate secret', exact: true }).click()
  await expect(page.locator('.settings-body')).toContainText('v2')
  await page.goto('http://localhost:5173/#/theater?id=RUN-0128')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download .evidence' }).click()
  const path = await (await download).path()
  const { integrity, ...payload } = JSON.parse(await readFile(path!, 'utf8'))
  const key = await page.evaluate(() => JSON.parse(localStorage.getItem('chaos-pact-v1:sandbox-hmac')!).value)
  expect(integrity.algorithm).toBe('HMAC-SHA256')
  expect(integrity.keyVersion).toBe(2)
  expect(integrity.signature).toBe(createHmac('sha256', key).update(JSON.stringify(payload)).digest('hex'))
})

